export type GameState = "intro" | "playing" | "feedback" | "finished";

export type OptionKey = "А" | "Б" | "В" | "Г";

export interface Option {
  key: OptionKey;
  text: string;
}

export interface Question {
  id: number; // 1..10
  /** Номер тематичного блоку (1..5). */
  blockNo: number;
  /** Назва когнітивного упередження (укр). */
  block: string;
  /** Оригінальний англійський термін. */
  blockEn: string;
  /** Тип стимулу — короткий підпис над «вирізкою». */
  source: string;
  /** Текст сценарію-стимулу. Фрагменти в **зірочках** підкреслюються. */
  stimulus: string;
  /** Опційні цитати видань — рендеряться окремими блоками з плашкою-підписом. */
  quotes?: { label: string; text: string }[];
  /** Саме питання. */
  prompt: string;
  options: Option[];
  correct: OptionKey;
  explanation: string;
}

export interface Level {
  title: string;
  min: number;
  max: number;
  range: string;
  description: string;
  /** Вирізаний персонаж (прозорий PNG) для картки результату. */
  character: string;
  /** slug шер-сторінки результату: /r/{slug}/ */
  slug: "novice" | "careful" | "master";
  /** Акцентний колір рівня (заголовок, коло, штамп). */
  accent: string;
  /** Текст, із яким шериться результат. */
  shareText: string;
}

